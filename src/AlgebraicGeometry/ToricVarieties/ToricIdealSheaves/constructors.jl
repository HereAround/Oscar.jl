# Toric Cox-ring ideal sheaves.

@doc raw"""
    ideal_sheaf(X::NormalToricVariety, I::MPolyIdeal)

Create a sheaf of ideals on a toric variety ``X`` from a homogeneous ideal
`I` in its `cox_ring`.

# Examples
```jldoctest
julia> P3 = projective_space(NormalToricVariety, 3)
Normal toric variety

julia> (x1,x2,x3,x4) = gens(cox_ring(P3));

julia> I = ideal([x2,x3])
Ideal generated by
  x2
  x3

julia> IdealSheaf(P3, I);
```
"""
ideal_sheaf(X::NormalToricVarietyType, I::MPolyIdeal) = ToricIdealSheafFromCoxRingIdeal(X, I)

function _dehomogenize_to_chart(X::NormalToricVarietyType, I::MPolyIdeal, k::Int)
  # We use CLS11, Proposition 5.2.10 and Exercise 5.2.5.
