# Interface for chosen complete-intersection presentations: implementations retain
# equations and divisor classes. Constructors check the CI condition by default;
# explicit opt-outs leave it assumed, and smoothness is checked only on request.
# General closed subschemes store only an ideal and do not implement this interface.
abstract type AbsToricCompleteIntersection end

# Retain the chosen equations alongside the existing closed-subscheme representation.
@attributes mutable struct ToricCompleteIntersection <: AbsToricCompleteIntersection
  subscheme::ClosedSubschemeOfToricVariety
  equations::Vector{MPolyDecRingElem{QQFieldElem,QQMPolyRingElem}}
  classes::Vector{ToricDivisorClass}
  function ToricCompleteIntersection(
    subscheme::ClosedSubschemeOfToricVariety,
    equations::Vector{MPolyDecRingElem{QQFieldElem,QQMPolyRingElem}},
    classes::Vector{ToricDivisorClass};
    check_smoothness::Bool=false, check_codimension::Bool=true,
  )
    Y = new(subscheme, equations, classes)
    _check_toric_presentation(Y; check_smoothness, check_codimension)
    return Y
  end
end

# A hypersurface wraps a one-equation presentation and shares its implementation.
@attributes mutable struct ToricHypersurface <: AbsToricCompleteIntersection
  presentation::ToricCompleteIntersection
  function ToricHypersurface(
    presentation::ToricCompleteIntersection;
    check_smoothness::Bool=false, check_codimension::Bool=true,
  )
    @req length(defining_equations(presentation)) == 1 "A hypersurface requires exactly one equation"
    Y = new(presentation)
    _check_toric_presentation(Y; check_smoothness, check_codimension)
    return Y
  end
end

_toric_presentation(Y::ToricCompleteIntersection) = Y
_toric_presentation(Y::ToricHypersurface) = Y.presentation

@doc raw"""
    closed_subscheme_of_toric_variety(Y::AbsToricCompleteIntersection)

Return the stored underlying closed subscheme of `Y`, retaining its scheme
structure. This accessor returns the same object on repeated calls and shares
its cached scheme computations with `Y`.
"""
closed_subscheme_of_toric_variety(Y::AbsToricCompleteIntersection) =
  _toric_presentation(Y).subscheme

@doc raw"""
    covered_scheme(Y::AbsToricCompleteIntersection)

Return a toric hypersurface or complete intersection as an OSCAR covered
scheme, preserving its nonreduced structure. This is the cached covered scheme
of the underlying closed subscheme. Conversion itself does not check
smoothness or expected codimension.
"""
covered_scheme(Y::AbsToricCompleteIntersection) =
  covered_scheme(closed_subscheme_of_toric_variety(Y))

@doc raw"""
    defining_equations(Y::AbsToricCompleteIntersection)

Return a copy of the chosen list of homogeneous Cox-ring equations of `Y`.
These are the original equations, not a new generating set of the defining ideal.
"""
defining_equations(Y::AbsToricCompleteIntersection) = copy(_toric_presentation(Y).equations)

@doc raw"""
    defining_divisor_classes(Y::AbsToricCompleteIntersection)

Return the divisor classes of the chosen defining equations, in the same order.
"""
defining_divisor_classes(Y::AbsToricCompleteIntersection) = copy(_toric_presentation(Y).classes)

@doc raw"""
    defining_equation(Y::ToricHypersurface)

Return the chosen homogeneous Cox-ring equation of `Y`.
"""
defining_equation(Y::ToricHypersurface) = only(defining_equations(Y))

@doc raw"""
    toric_variety(Y::AbsToricCompleteIntersection)

Return the ambient toric variety of `Y`.
"""
toric_variety(Y::AbsToricCompleteIntersection) =
  toric_variety(closed_subscheme_of_toric_variety(Y))

@doc raw"""
    defining_ideal(Y::AbsToricCompleteIntersection)

Return the Cox-ring ideal generated by the chosen equations of `Y`.
"""
defining_ideal(Y::AbsToricCompleteIntersection) =
  defining_ideal(closed_subscheme_of_toric_variety(Y))

@doc raw"""
    radical(Y::AbsToricCompleteIntersection)

Return the radical of the stored Cox-ring ideal of `Y`, without saturation.
This is not the scheme-theoretic reduction or a reducedness test.
"""
radical(Y::AbsToricCompleteIntersection) = radical(closed_subscheme_of_toric_variety(Y))

@doc raw"""
    is_empty(Y::AbsToricCompleteIntersection)

Check whether the underlying closed subscheme of `Y` is empty.
"""
is_empty(Y::AbsToricCompleteIntersection) = is_empty(closed_subscheme_of_toric_variety(Y))

@doc raw"""
    dim(Y::AbsToricCompleteIntersection)

Return the dimension of the associated scheme, including for an unchecked
presentation. The empty scheme has dimension `-inf`.
"""
dim(Y::AbsToricCompleteIntersection) = dim(covered_scheme(Y))

@doc raw"""
    is_reduced(Y::AbsToricCompleteIntersection)

Test reducedness of the associated scheme, including for a hypersurface.
The stored Cox ideal need not be radical for this property to hold.
"""
is_reduced(Y::AbsToricCompleteIntersection) = is_reduced(covered_scheme(Y))

@doc raw"""
    is_irreducible(Y::AbsToricCompleteIntersection)

Test irreducibility of the associated scheme. The empty scheme is not irreducible.
"""
is_irreducible(Y::AbsToricCompleteIntersection) =
  is_irreducible(closed_subscheme_of_toric_variety(Y))

@doc raw"""
    is_integral(Y::AbsToricCompleteIntersection)

Test whether the associated scheme is nonempty, reduced, and irreducible.
This does not assert geometric integrality.
"""
is_integral(Y::AbsToricCompleteIntersection) = is_integral(covered_scheme(Y))

function _toric_equations(X::NormalToricVariety, equations::AbstractVector)
  @req 1 <= length(equations) <= dim(X) "Provide between one and dim(X) defining equations"
  R = cox_ring(X)
  @req all(f -> f isa MPolyDecRingElem && parent(f) === R, equations) "Equations must belong to the ambient Cox ring"
  @req all(f -> !iszero(f) && !is_constant(f), equations) "Defining equations must be nonzero and nonconstant"
  @req all(is_homogeneous, equations) "Defining equations must be homogeneous in the Cox grading"
  return elem_type(R)[deepcopy(f) for f in equations]
end

@doc raw"""
    toric_complete_intersection(X::NormalToricVariety, equations::AbstractVector;
                               check_smoothness=false, check_codimension=true)
    toric_complete_intersection(Y::ClosedSubschemeOfToricVariety, equations::AbstractVector;
                               check_smoothness=false, check_codimension=true)

Retain a chosen presentation by nonzero, nonconstant homogeneous Cox-ring
equations in a simplicial toric variety. When supplying an existing subscheme,
the equations must generate its defining ideal. No presentation is inferred
from arbitrary ideal generators.

By default, require Cartier defining classes and a nonempty subscheme of
codimension equal to the number of equations. Since normal toric varieties
are Cohen--Macaulay, the corresponding local equations then form a regular
sequence along the subscheme. Non-Cartier presentations on singular ambient
varieties are not certified by this check. Set `check_codimension=false` to
assume these conditions; no positive check result is cached when it is skipped.

Complete intersections may be singular or nonreduced. Smoothness is unknown
unless `check_smoothness=true`, which checks the associated scheme and rejects
a singular subscheme. This is independent of the complete-intersection check.
Errors in scheme computations propagate.
"""
function toric_complete_intersection(
  X::NormalToricVariety, equations::AbstractVector;
  check_smoothness::Bool=false, check_codimension::Bool=true,
)
  fs = _toric_equations(X, equations)
  c = closed_subscheme_of_toric_variety(X, fs)
  return ToricCompleteIntersection(
    c, fs, [toric_divisor_class(X, degree(f)) for f in fs]; check_smoothness, check_codimension,
  )
end

function toric_complete_intersection(
  c::ClosedSubschemeOfToricVariety, equations::AbstractVector;
  check_smoothness::Bool=false, check_codimension::Bool=true,
)
  X = toric_variety(c)
  @req X isa NormalToricVariety "A normal toric ambient variety is required"
  fs = _toric_equations(X, equations)
  @req ideal(cox_ring(X), fs) == defining_ideal(c) "The supplied equations must generate the defining ideal"
  return ToricCompleteIntersection(
    c, fs, [toric_divisor_class(X, degree(f)) for f in fs]; check_smoothness, check_codimension,
  )
end

@doc raw"""
    toric_hypersurface(X::NormalToricVariety, f::MPolyDecRingElem;
                      check_smoothness=false, check_codimension=true)
    toric_hypersurface(Y::ClosedSubschemeOfToricVariety, f::MPolyDecRingElem;
                      check_smoothness=false, check_codimension=true)

Construct a toric hypersurface retaining the actual homogeneous equation `f`.
The hypersurface may be singular or nonreduced. By default, require a Cartier
defining class and a nonempty subscheme of codimension one. Set
`check_codimension=false` to assume these conditions. Independently, set
`check_smoothness=true` to require smoothness; otherwise smoothness remains
unknown. With an existing subscheme `Y`, the ideal `(f)` must equal its stored
Cox ideal. The options have the same meaning as for
[`toric_complete_intersection`](@ref).
"""
function toric_hypersurface(
  X::Union{NormalToricVariety,ClosedSubschemeOfToricVariety}, f::MPolyDecRingElem;
  check_smoothness::Bool=false, check_codimension::Bool=true,
)
  presentation = toric_complete_intersection(X, [f]; check_codimension=false)
  return ToricHypersurface(presentation; check_smoothness, check_codimension)
end

@doc raw"""
    is_smooth(Y::AbsToricCompleteIntersection)

Check smoothness of the scheme defined by the chosen equations, using the
toric ideal sheaf and OSCAR's covered-scheme smoothness test.
This applies to both toric hypersurfaces and toric complete intersections.
"""
@attr Bool is_smooth(Y::AbsToricCompleteIntersection) =
  is_smooth(closed_subscheme_of_toric_variety(Y))

@doc raw"""
    has_expected_codimension(Y::AbsToricCompleteIntersection)

Check that the associated scheme is nonempty and has codimension equal to
the number of chosen equations. For a toric hypersurface, the expected
codimension is one. This check is independent of smoothness, and singular or
nonreduced complete intersections may pass it. In a smooth ambient variety it
implies that the equations locally define a complete intersection. On a singular
ambient variety, Cartier defining classes are also sufficient. The dimension
test alone does not certify this for non-Cartier presentations. The result is
cached only after the computation finishes.
"""
@attr Bool function has_expected_codimension(Y::AbsToricCompleteIntersection)
  return !is_empty(Y) && dim(Y) == dim(toric_variety(Y)) - length(defining_equations(Y))
end

function _check_toric_presentation(
  Y::AbsToricCompleteIntersection;
  check_smoothness::Bool=false, check_codimension::Bool=false,
)
  if check_codimension
    X = toric_variety(Y)
    @req is_smooth(X) || all(D -> is_cartier(toric_divisor(D)), defining_divisor_classes(Y)) "Checking a complete intersection requires Cartier defining classes"
    @req has_expected_codimension(Y) "The equations do not have the expected codimension"
  end
  if check_smoothness
    @req is_smooth(Y) "The defined subscheme is singular"
  end
  return nothing
end

function _check_toric_euler_ambient(
  X::NormalToricVariety, classes::AbstractVector{ToricDivisorClass};
  completeness_check::Bool=true,
)
  @req is_smooth(X) "Intersection theory requires a smooth ambient toric variety"
  if completeness_check
    @req is_complete(X) "Intersection theory requires a complete ambient toric variety"
  end
  @req 1 <= length(classes) <= dim(X) "Provide between one and dim(X) divisor classes"
  @req all(D -> toric_variety(D) === X, classes) "All divisor classes must belong to the ambient variety"
  return nothing
end

function _check_toric_euler_presentation(
  Y::AbsToricCompleteIntersection;
  completeness_check::Bool=true, check_smoothness::Bool=false,
  check_codimension::Bool=false,
)
  _check_toric_euler_ambient(toric_variety(Y), defining_divisor_classes(Y); completeness_check)
  _check_toric_presentation(Y; check_smoothness, check_codimension)
  c = closed_subscheme_of_toric_variety(Y)
  @req !has_attribute(c, :is_smooth) || get_attribute(c, :is_smooth) "The defined subscheme is known to be singular"
  for Z in (Y, _toric_presentation(Y))
    @req !has_attribute(Z, :has_expected_codimension) || get_attribute(Z, :has_expected_codimension) "The equations are known not to have the expected codimension"
  end
  return nothing
end

function _toric_complete_intersection_chern_polynomial(
  X::NormalToricVariety, classes::AbstractVector{ToricDivisorClass}, k::Int;
  completeness_check::Bool=true,
)
  # Division by each (1 + D) is a finite recurrence, truncated at degree k.
  cs = [polynomial(chern_class(X, j; completeness_check)) for j in 0:k]
  for D in classes
    d = polynomial(cohomology_class(D; completeness_check))
    for j in 1:k
      cs[j + 1] = cs[j + 1] - d * cs[j]
    end
  end
  return cs[k + 1]
end

@doc raw"""
    chern_class(Y::AbsToricCompleteIntersection, k::Int;
                completeness_check=true, check_smoothness=false, check_codimension=false)

Return an ambient cohomology class whose restriction to a smooth complete
intersection `Y` is its `k`-th tangent Chern class. The ambient toric variety
must be smooth and complete. Unless explicitly checked, smoothness of `Y`
and the expected-codimension (regular-sequence) condition are assumptions.
`completeness_check=false` skips only ambient completeness verification.
"""
function chern_class(
  Y::AbsToricCompleteIntersection, k::Int;
  completeness_check::Bool=true, check_smoothness::Bool=false,
  check_codimension::Bool=false,
)
  X = toric_variety(Y)
  classes = defining_divisor_classes(Y)
  @req 0 <= k <= dim(X) - length(classes) "Chern class index must lie between zero and the expected dimension"
  _check_toric_euler_presentation(Y; completeness_check, check_smoothness, check_codimension)
  cohomology_ring(X; completeness_check)
  p = _toric_complete_intersection_chern_polynomial(X, classes, k; completeness_check)
  return cohomology_class(X, p; completeness_check)
end

@doc raw"""
    euler_characteristic(X::NormalToricVariety, classes::AbstractVector{ToricDivisorClass};
                         algorithm=:intersection_theory, completeness_check=true)

Compute the Euler characteristic of a **smooth member**, assuming one exists,
of the expected codimension with the listed divisor classes in a smooth,
complete toric variety `X`. This numerical calculation does not specify or
check any equations. It is not the Euler characteristic of a singular member.

The intersection-theory algorithm integrates the degree-`dim(X)` part of
``c(TX)\prod_i D_i/(1+D_i)`` using exact arithmetic and finite degree
truncation. The result must be integral and is returned as a `ZZRingElem`.
`completeness_check=false` skips only completeness verification; ambient
smoothness and input validation are always checked, even with cached data.
"""
function euler_characteristic(
  X::NormalToricVariety, classes::AbstractVector{ToricDivisorClass};
  algorithm::Symbol=:intersection_theory, completeness_check::Bool=true,
)
  @req algorithm == :intersection_theory "Unknown Euler characteristic algorithm"
  _check_toric_euler_ambient(X, classes; completeness_check)
  cohomology_ring(X; completeness_check)
  k = dim(X) - length(classes)
  p = _toric_complete_intersection_chern_polynomial(X, classes, k; completeness_check)
  for D in classes
    p *= polynomial(cohomology_class(D; completeness_check))
  end
  value = integrate(cohomology_class(X, p; completeness_check); completeness_check)
  @req isone(denominator(value)) "The intersection-theory Euler characteristic is not integral"
  return ZZ(value)
end

@doc raw"""
    euler_characteristic(Y::AbsToricCompleteIntersection;
                         algorithm=:intersection_theory, completeness_check=true,
                         check_smoothness=false, check_codimension=false)

Compute the Euler characteristic by ambient intersection theory, assuming `Y`
is smooth and its equations locally form a regular sequence of the expected
codimension. The ambient toric variety must be smooth and complete.

Set `check_smoothness=true` and `check_codimension=true` to verify these two
independent assumptions using the associated scheme. Skipped checks remain
unknown; known failures are rejected even when checking is disabled. In
particular, a smoothness check alone does not establish the codimension.
No Euler cache bypasses a requested check or algorithm selection.
See also the class-only method for numerical invariants of smooth members.
"""
function euler_characteristic(
  Y::AbsToricCompleteIntersection;
  algorithm::Symbol=:intersection_theory, completeness_check::Bool=true,
  check_smoothness::Bool=false, check_codimension::Bool=false,
)
  @req algorithm == :intersection_theory "Unknown Euler characteristic algorithm"
  _check_toric_euler_presentation(Y; completeness_check, check_smoothness, check_codimension)
  return euler_characteristic(toric_variety(Y), defining_divisor_classes(Y); algorithm, completeness_check)
end

